CREATE TABLE IF NOT EXISTS public.world_mail (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 500),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  CONSTRAINT world_mail_no_self CHECK (sender_id <> recipient_id)
);
CREATE INDEX IF NOT EXISTS world_mail_recipient_recent ON public.world_mail (recipient_id, created_at DESC);
CREATE INDEX IF NOT EXISTS world_mail_sender_recent ON public.world_mail (sender_id, created_at DESC);
ALTER TABLE public.world_mail ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.world_mail FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.world_mail_id_seq FROM PUBLIC, anon, authenticated;

-- SECURITY DEFINER: accesul la toate mesajele se face strict prin aceste RPC-uri;
-- nu există politici care permit citirea directă a tabelului.
CREATE OR REPLACE FUNCTION public.world_mail_send(p_target uuid, p_body text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := auth.uid();
  v_body text := btrim(COALESCE(p_body, ''));
  v_id bigint;
  v_name text;
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  IF p_target IS NULL OR p_target = v_uid THEN RAISE EXCEPTION 'Destinatar invalid.'; END IF;
  IF char_length(v_body) < 1 OR char_length(v_body) > 500 THEN
    RAISE EXCEPTION 'Mesajul trebuie să conțină între 1 și 500 de caractere.';
  END IF;
  IF v_body ~ '[[:cntrl:]]' THEN RAISE EXCEPTION 'Mesajul conține caractere nepermise.'; END IF;
  -- Doar persoane care și-au creat satul în aceeași Lume BETA.
  SELECT name INTO v_name FROM public.world_players WHERE user_id = p_target;
  IF NOT FOUND THEN RAISE EXCEPTION 'Destinatarul nu mai este pe hartă.'; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.world_players WHERE user_id = v_uid) THEN
    RAISE EXCEPTION 'Intră mai întâi în Lume pentru a trimite mesaje.';
  END IF;
  -- Protecție anti-spam. Advisory lock serializează cererile concurente ale aceluiași expeditor.
  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(v_uid::text, 4289));
  IF EXISTS (
    SELECT 1 FROM public.world_mail
    WHERE sender_id = v_uid AND created_at > clock_timestamp() - interval '30 seconds'
  ) THEN RAISE EXCEPTION 'Poți trimite un mesaj la 30 de secunde.'; END IF;
  IF (SELECT count(*) FROM public.world_mail
      WHERE sender_id = v_uid AND created_at > clock_timestamp() - interval '24 hours') >= 30 THEN
    RAISE EXCEPTION 'Ai atins limita de 30 de mesaje în 24 de ore.';
  END IF;
  INSERT INTO public.world_mail(sender_id,recipient_id,body)
  VALUES (v_uid,p_target,v_body) RETURNING id INTO v_id;
  RETURN jsonb_build_object('id',v_id,'to',v_name);
END
$fn$;

CREATE OR REPLACE FUNCTION public.world_mail_inbox()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := auth.uid();
  v_msgs jsonb;
  v_unread integer;
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  SELECT count(*)::integer INTO v_unread
  FROM public.world_mail WHERE recipient_id=v_uid AND read_at IS NULL;

  SELECT COALESCE(jsonb_agg(v.item ORDER BY v.created_at DESC,v.id DESC),'[]'::jsonb)
  INTO v_msgs FROM (
    SELECT m.id, m.created_at,
      jsonb_build_object(
        'id',m.id,'from_id',m.sender_id,
        'from',COALESCE(p.name,'Jucător'),
        'body',m.body,
        'at',(extract(epoch FROM m.created_at)*1000)::bigint,
        'read',m.read_at IS NOT NULL
      ) AS item
    FROM public.world_mail m
    LEFT JOIN public.world_players p ON p.user_id=m.sender_id
    WHERE m.recipient_id=v_uid
    ORDER BY m.created_at DESC,m.id DESC LIMIT 50
  ) v;
  RETURN jsonb_build_object('unread',v_unread,'messages',v_msgs);
END
$fn$;

CREATE OR REPLACE FUNCTION public.world_mail_read(p_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE v_uid uuid := auth.uid();
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  UPDATE public.world_mail
    SET read_at=COALESCE(read_at,clock_timestamp())
    WHERE id=p_id AND recipient_id=v_uid;
  IF NOT FOUND THEN RAISE EXCEPTION 'Mesajul nu există în inboxul tău.'; END IF;
  RETURN jsonb_build_object('ok',true);
END
$fn$;

REVOKE ALL ON FUNCTION public.world_mail_send(uuid,text) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.world_mail_inbox() FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.world_mail_read(bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.world_mail_send(uuid,text) TO authenticated;
GRANT EXECUTE ON FUNCTION public.world_mail_inbox() TO authenticated;
GRANT EXECUTE ON FUNCTION public.world_mail_read(bigint) TO authenticated;
COMMIT;

