-- Silver Throne BETA SQL42: chatul breslei.
-- Rulati DOAR in Supabase Silver-Throne-Test DUPA supabase/14 si 15 (bresle + ranguri).
-- Nu modifica breslele, membrii, contractele, bossul sau salvarile.
--
-- Reguli:
--  * doar membrii breslei citesc si scriu in chatul ei (rolul si bresla se citesc din guild_members,
--    niciodata din ce trimite browserul);
--  * mesaj de 1..300 de caractere, fara rand nou multiplu; maximum 1 mesaj la 2 secunde si 12 pe minut;
--  * autorul isi poate sterge mesajul; conducatorul si ofiterii pot sterge orice mesaj din bresla;
--  * se pastreaza ultimele 500 de mesaje pe breasla; cele mai vechi se curata automat.
BEGIN;

CREATE TABLE IF NOT EXISTS public.guild_chat_messages (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guild_id bigint NOT NULL REFERENCES public.guilds(id) ON DELETE CASCADE,
 user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 author text NOT NULL,
 body text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 deleted_at timestamptz,
 deleted_by uuid,
 CONSTRAINT guild_chat_body_size CHECK (char_length(body) BETWEEN 1 AND 300),
 CONSTRAINT guild_chat_author_size CHECK (char_length(author) BETWEEN 1 AND 20)
);
CREATE INDEX IF NOT EXISTS guild_chat_guild_idx ON public.guild_chat_messages(guild_id,id DESC);
CREATE INDEX IF NOT EXISTS guild_chat_user_idx ON public.guild_chat_messages(user_id,created_at DESC);
ALTER TABLE public.guild_chat_messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.guild_chat_messages FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.guild_chat_messages_id_seq FROM PUBLIC,anon,authenticated;

-- p_action: 'list' (p_data.after = ultimul id vazut, optional) | 'send' (p_data.body) | 'delete' (p_data.id)
CREATE OR REPLACE FUNCTION public.guild_chat_api(
 p_action text DEFAULT 'list', p_data jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $chat$
DECLARE
 v_uid uuid:=auth.uid();
 v_action text:=lower(trim(coalesce(p_action,'list')));
 v_me public.guild_members%ROWTYPE;
 v_body text;
 v_name text;
 v_after bigint;
 v_id bigint;
 v_msg public.guild_chat_messages%ROWTYPE;
 v_mod boolean;
 v_rows jsonb;
BEGIN
 IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
  RAISE EXCEPTION 'Acces permis doar administratorilor BETA.';
 END IF;
 p_data:=coalesce(p_data,'{}'::jsonb);
 SELECT * INTO v_me FROM public.guild_members WHERE user_id=v_uid;
 IF v_me.user_id IS NULL THEN
  RAISE EXCEPTION 'Nu esti membru al unei bresle.';
 END IF;
 v_mod:=v_me.role IN ('leader','officer');

 IF v_action='send' THEN
  -- spatiile multiple si randurile goale se strang; textul se taie la 300 de caractere
  v_body:=left(btrim(regexp_replace(coalesce(p_data->>'body',''),'\s+',' ','g')),300);
  IF v_body='' THEN RAISE EXCEPTION 'Scrie un mesaj.'; END IF;
  IF EXISTS(SELECT 1 FROM public.guild_chat_messages
            WHERE user_id=v_uid AND created_at>now()-interval '2 seconds') THEN
   RAISE EXCEPTION 'Prea repede. Asteapta o clipa.';
  END IF;
  IF (SELECT count(*) FROM public.guild_chat_messages
      WHERE user_id=v_uid AND created_at>now()-interval '1 minute')>=12 THEN
   RAISE EXCEPTION 'Ai trimis prea multe mesaje. Mai incearca peste un minut.';
  END IF;
  SELECT left(coalesce(nullif(btrim(w.name),''),'Erou'),20) INTO v_name
    FROM public.world_players w WHERE w.user_id=v_uid;
  v_name:=coalesce(v_name,'Erou');
  INSERT INTO public.guild_chat_messages(guild_id,user_id,author,body)
   VALUES(v_me.guild_id,v_uid,v_name,v_body) RETURNING id INTO v_id;
  -- pastreaza doar ultimele 500 de mesaje ale breslei
  DELETE FROM public.guild_chat_messages m
   WHERE m.guild_id=v_me.guild_id
     AND m.id<(SELECT x.id FROM public.guild_chat_messages x WHERE x.guild_id=v_me.guild_id
               ORDER BY x.id DESC OFFSET 499 LIMIT 1);
  v_after:=nullif(p_data->>'after','')::bigint;

 ELSIF v_action='delete' THEN
  v_id:=nullif(p_data->>'id','')::bigint;
  SELECT * INTO v_msg FROM public.guild_chat_messages WHERE id=v_id AND guild_id=v_me.guild_id;
  IF v_msg.id IS NULL THEN RAISE EXCEPTION 'Mesajul nu exista.'; END IF;
  IF v_msg.user_id<>v_uid AND NOT v_mod THEN
   RAISE EXCEPTION 'Poti sterge doar mesajele tale.';
  END IF;
  UPDATE public.guild_chat_messages SET deleted_at=now(),deleted_by=v_uid,body='-'
   WHERE id=v_msg.id AND deleted_at IS NULL;
  v_after:=NULL;

 ELSIF v_action='list' THEN
  v_after:=nullif(p_data->>'after','')::bigint;
 ELSE
  RAISE EXCEPTION 'Actiune necunoscuta.';
 END IF;

 -- ultimele 60 de mesaje (sau doar cele noi, dupa „after”), in ordine cronologica
 SELECT coalesce(jsonb_agg(jsonb_build_object(
   'id',q.id,'author',q.author,'body',CASE WHEN q.deleted_at IS NULL THEN q.body ELSE NULL END,
   'deleted',q.deleted_at IS NOT NULL,'mine',q.user_id=v_uid,
   'can_delete',q.deleted_at IS NULL AND (q.user_id=v_uid OR v_mod),
   'at',(extract(epoch FROM q.created_at)*1000)::bigint) ORDER BY q.id),'[]'::jsonb)
  INTO v_rows
  FROM (SELECT * FROM public.guild_chat_messages m
        WHERE m.guild_id=v_me.guild_id AND (v_after IS NULL OR m.id>v_after)
        ORDER BY m.id DESC LIMIT 60) q;

 RETURN jsonb_build_object('ok',true,'guild_id',v_me.guild_id,'full',v_after IS NULL,
  'messages',v_rows,
  'last_id',(SELECT max(id) FROM public.guild_chat_messages WHERE guild_id=v_me.guild_id));
END $chat$;
REVOKE ALL ON FUNCTION public.guild_chat_api(text,jsonb) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.guild_chat_api(text,jsonb) TO authenticated;
COMMIT;
