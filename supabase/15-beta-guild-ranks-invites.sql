-- Silver Throne BETA: ranguri de breasla + invitatii directe intre jucatori.
-- Rulati DOAR in Supabase Silver-Throne-Test DUPA supabase/14-beta-guilds.sql.
-- Migrare fara resetarea breslelor, membrilor, contractelor sau bossului.
BEGIN;

-- Ranguri: conducator (leader), ofiter (officer), veteran, membru (member).
-- Membrii si rangurile deja existente isi pastreaza valorile.
ALTER TABLE public.guild_members DROP CONSTRAINT IF EXISTS guild_members_role_check;
ALTER TABLE public.guild_members
 ADD CONSTRAINT guild_members_role_check
 CHECK (role IN ('leader','officer','veteran','member'));

CREATE TABLE IF NOT EXISTS public.guild_invitations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 guild_id bigint NOT NULL REFERENCES public.guilds(id) ON DELETE CASCADE,
 inviter uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 invitee uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 status text NOT NULL DEFAULT 'pending'
   CHECK (status IN ('pending','accepted','declined','cancelled','expired')),
 created_at timestamptz NOT NULL DEFAULT now(),
 expires_at timestamptz NOT NULL DEFAULT (now() + interval '7 days'),
 responded_at timestamptz,
 CONSTRAINT guild_invitation_distinct CHECK (inviter<>invitee)
);
CREATE UNIQUE INDEX IF NOT EXISTS guild_invitation_one_pending
 ON public.guild_invitations(guild_id,invitee) WHERE status='pending';
CREATE INDEX IF NOT EXISTS guild_invitation_inbox_idx
 ON public.guild_invitations(invitee,created_at DESC);
CREATE INDEX IF NOT EXISTS guild_invitation_guild_idx
 ON public.guild_invitations(guild_id,created_at DESC);
CREATE INDEX IF NOT EXISTS guild_invitation_sender_idx
 ON public.guild_invitations(inviter,created_at DESC);
ALTER TABLE public.guild_invitations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.guild_invitations FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.guild_invitations_id_seq FROM PUBLIC,anon,authenticated;

-- Toate operatiile sociale trec prin acest RPC cu verificarea serverului BETA.
-- Nu folosim niciodata rangul, numele sau ID-ul breslei trimis de browser
-- ca dovada a drepturilor: rolul este citit direct din guild_members.
CREATE OR REPLACE FUNCTION public.guild_social_api(
 p_action text DEFAULT 'status', p_data jsonb DEFAULT '{}'::jsonb)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
 v_uid uuid:=auth.uid();
 v_action text:=lower(trim(coalesce(p_action,'status')));
 v_me public.guild_members%ROWTYPE;
 v_target public.guild_members%ROWTYPE;
 v_inv public.guild_invitations%ROWTYPE;
 v_target_id uuid;
 v_g public.guilds%ROWTYPE;
 v_inv_id bigint;
 v_rank text;
 v_q text;
 v_count integer;
 v_incoming jsonb:='[]'::jsonb;
 v_outgoing jsonb:='[]'::jsonb;
 v_members jsonb:='[]'::jsonb;
 v_results jsonb:='[]'::jsonb;
BEGIN
 IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
  RAISE EXCEPTION 'Acces permis doar administratorilor BETA.';
 END IF;
 p_data:=coalesce(p_data,'{}'::jsonb);
 SELECT * INTO v_me FROM public.guild_members WHERE user_id=v_uid;

 IF v_action='invite' THEN
  IF v_me.user_id IS NULL OR v_me.role NOT IN ('leader','officer') THEN
   RAISE EXCEPTION 'Doar conducatorul si ofiterii pot invita jucatori.';
  END IF;
  v_target_id:=nullif(p_data->>'user_id','')::uuid;
  IF v_target_id IS NULL OR v_target_id=v_uid
    OR NOT EXISTS(SELECT 1 FROM public.world_players WHERE user_id=v_target_id) THEN
   RAISE EXCEPTION 'Alege un jucator din Lume.';
  END IF;
  SELECT * INTO v_g FROM public.guilds WHERE id=v_me.guild_id FOR UPDATE;
  SELECT count(*) INTO v_count FROM public.guild_members WHERE guild_id=v_me.guild_id;
  IF v_count>=20 THEN RAISE EXCEPTION 'Breasla are deja 20 de membri.'; END IF;
  IF EXISTS(SELECT 1 FROM public.guild_members WHERE user_id=v_target_id) THEN
   RAISE EXCEPTION 'Jucatorul este deja intr-o breasla.';
  END IF;
  SELECT count(*) INTO v_count FROM public.guild_invitations
   WHERE inviter=v_uid AND created_at>now()-interval '24 hours';
  IF v_count>=12 THEN RAISE EXCEPTION 'Ai trimis deja 12 invitatii in ultimele 24 de ore.'; END IF;
  IF EXISTS(SELECT 1 FROM public.guild_invitations
    WHERE inviter=v_uid AND invitee=v_target_id AND created_at>now()-interval '24 hours'
      AND status IN('pending','declined','cancelled')) THEN
   RAISE EXCEPTION 'Acest jucator a primit deja o invitatie de la tine recent.';
  END IF;
  UPDATE public.guild_invitations SET status='expired',responded_at=now()
   WHERE guild_id=v_me.guild_id AND invitee=v_target_id
     AND status='pending' AND expires_at<=now();
  INSERT INTO public.guild_invitations(guild_id,inviter,invitee)
    VALUES(v_me.guild_id,v_uid,v_target_id);

 ELSIF v_action IN ('accept','decline') THEN
  v_inv_id:=nullif(p_data->>'invite_id','')::bigint;
  SELECT * INTO v_inv FROM public.guild_invitations
   WHERE id=v_inv_id AND invitee=v_uid AND status='pending' FOR UPDATE;
  IF NOT FOUND OR v_inv.expires_at<=now() THEN
   RAISE EXCEPTION 'Invitatia nu mai este valabila.';
  END IF;
  IF v_action='accept' THEN
   IF v_me.user_id IS NOT NULL THEN
    RAISE EXCEPTION 'Paraseste breasla actuala pentru a accepta o invitatie.';
   END IF;
   SELECT * INTO v_g FROM public.guilds WHERE id=v_inv.guild_id FOR UPDATE;
   IF NOT FOUND THEN RAISE EXCEPTION 'Breasla nu mai exista.'; END IF;
   SELECT count(*) INTO v_count FROM public.guild_members WHERE guild_id=v_inv.guild_id;
   IF v_count>=20 THEN RAISE EXCEPTION 'Breasla a atins limita de 20 de membri.'; END IF;
   INSERT INTO public.guild_members(user_id,guild_id,role)
     VALUES(v_uid,v_inv.guild_id,'member');
  END IF;
  UPDATE public.guild_invitations SET status=CASE WHEN v_action='accept'
      THEN 'accepted' ELSE 'declined' END,responded_at=now()
   WHERE id=v_inv_id;
  IF v_action='accept' THEN
   UPDATE public.guild_invitations SET status='declined',responded_at=now()
    WHERE invitee=v_uid AND status='pending' AND id<>v_inv_id;
  END IF;

 ELSIF v_action='cancel' THEN
  IF v_me.user_id IS NULL OR v_me.role NOT IN('leader','officer') THEN
   RAISE EXCEPTION 'Nu poti anula invitatii.';
  END IF;
  v_inv_id:=nullif(p_data->>'invite_id','')::bigint;
  SELECT * INTO v_inv FROM public.guild_invitations
   WHERE id=v_inv_id AND guild_id=v_me.guild_id AND status='pending' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Invitatie necunoscuta.'; END IF;
  IF v_me.role='officer' AND v_inv.inviter<>v_uid THEN
   RAISE EXCEPTION 'Ofiterii pot anula doar invitatiile proprii.';
  END IF;
  UPDATE public.guild_invitations SET status='cancelled',responded_at=now()
    WHERE id=v_inv.id;

 ELSIF v_action IN ('rank','transfer','kick') THEN
  IF v_me.user_id IS NULL THEN RAISE EXCEPTION 'Nu esti intr-o breasla.'; END IF;
  SELECT * INTO v_g FROM public.guilds WHERE id=v_me.guild_id FOR UPDATE;
  v_target_id:=nullif(p_data->>'user_id','')::uuid;
  SELECT * INTO v_target FROM public.guild_members
   WHERE user_id=v_target_id AND guild_id=v_me.guild_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Jucatorul nu este membru al breslei.'; END IF;
  IF v_target.user_id=v_uid THEN RAISE EXCEPTION 'Nu iti poti modifica singur rangul.'; END IF;
  IF v_target.role='leader' THEN RAISE EXCEPTION 'Conducatorul nu poate fi modificat astfel.'; END IF;
  IF v_action='rank' THEN
   IF v_me.role<>'leader' THEN RAISE EXCEPTION 'Doar conducatorul modifica ranguri.'; END IF;
   v_rank:=lower(coalesce(p_data->>'role',''));
   IF v_rank NOT IN('officer','veteran','member') THEN
    RAISE EXCEPTION 'Rang necunoscut.';
   END IF;
   UPDATE public.guild_members SET role=v_rank WHERE user_id=v_target.user_id;
  ELSIF v_action='transfer' THEN
   IF v_me.role<>'leader' THEN RAISE EXCEPTION 'Doar conducatorul poate preda conducerea.'; END IF;
   UPDATE public.guild_members SET role='officer' WHERE user_id=v_uid;
   UPDATE public.guild_members SET role='leader' WHERE user_id=v_target.user_id;
   UPDATE public.guilds SET founder=v_target.user_id WHERE id=v_me.guild_id;
  ELSE
   IF v_me.role NOT IN('leader','officer')
      OR (v_me.role='officer' AND v_target.role<>'member') THEN
    RAISE EXCEPTION 'Nu ai dreptul sa elimini acest membru.';
   END IF;
   DELETE FROM public.guild_members WHERE user_id=v_target.user_id;
  END IF;
 ELSIF v_action NOT IN ('status','search') THEN
  RAISE EXCEPTION 'Actiune necunoscuta.';
 END IF;

 SELECT * INTO v_me FROM public.guild_members WHERE user_id=v_uid;
 -- Inbox: fiecare persoana vede doar invitatiile proprii, nu pe ale altora.
 SELECT coalesce(jsonb_agg(jsonb_build_object(
   'id',i.id,'guild_name',g.name,'guild_tag',g.tag,
   'inviter',coalesce(w.name,'Erou'),'expires_at',i.expires_at)
   ORDER BY i.created_at DESC),'[]'::jsonb)
 INTO v_incoming
 FROM public.guild_invitations i
 JOIN public.guilds g ON g.id=i.guild_id
 LEFT JOIN public.world_players w ON w.user_id=i.inviter
 WHERE i.invitee=v_uid AND i.status='pending' AND i.expires_at>now();

 IF v_me.user_id IS NOT NULL THEN
  SELECT coalesce(jsonb_agg(jsonb_build_object(
    'user_id',m.user_id,'name',coalesce(w.name,'Erou'),
    'role',m.role,'level',coalesce(w.level,1))
    ORDER BY CASE m.role WHEN 'leader' THEN 0 WHEN 'officer' THEN 1
      WHEN 'veteran' THEN 2 ELSE 3 END, m.joined_at),'[]'::jsonb)
   INTO v_members
   FROM public.guild_members m
   LEFT JOIN public.world_players w ON w.user_id=m.user_id
   WHERE m.guild_id=v_me.guild_id;

  IF v_me.role IN ('leader','officer') THEN
   SELECT coalesce(jsonb_agg(jsonb_build_object(
    'id',i.id,'name',coalesce(w.name,'Erou'),'inviter_id',i.inviter,
    'expires_at',i.expires_at) ORDER BY i.created_at DESC),'[]'::jsonb)
   INTO v_outgoing
   FROM public.guild_invitations i
   LEFT JOIN public.world_players w ON w.user_id=i.invitee
   WHERE i.guild_id=v_me.guild_id AND i.status='pending' AND i.expires_at>now();

   IF v_action='search' THEN
    v_q:=trim(coalesce(p_data->>'query',''));
    IF char_length(v_q) BETWEEN 2 AND 40 THEN
     SELECT coalesce(jsonb_agg(jsonb_build_object(
       'user_id',q.user_id,'name',q.name,'level',q.level,
       'invited',q.invited) ORDER BY q.name),'[]'::jsonb)
     INTO v_results
     FROM (
       SELECT w.user_id,w.name,w.level,
        EXISTS(SELECT 1 FROM public.guild_invitations gi
         WHERE gi.guild_id=v_me.guild_id AND gi.invitee=w.user_id
          AND gi.status='pending' AND gi.expires_at>now()) AS invited
       FROM public.world_players w
       WHERE w.user_id<>v_uid
         AND strpos(lower(w.name),lower(v_q))>0
         AND NOT EXISTS(SELECT 1 FROM public.guild_members gm WHERE gm.user_id=w.user_id)
       ORDER BY lower(w.name),w.user_id LIMIT 15
     ) q;
    END IF;
   END IF;
  END IF;
 END IF;
 RETURN jsonb_build_object(
  'role',CASE WHEN v_me.user_id IS NULL THEN null ELSE v_me.role END,
  'guild_id',CASE WHEN v_me.user_id IS NULL THEN null ELSE v_me.guild_id END,
  'invitations',v_incoming,'outgoing',v_outgoing,
  'members',v_members,'results',v_results,'at',now());
END $function$;
REVOKE ALL ON FUNCTION public.guild_social_api(text,jsonb)
  FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.guild_social_api(text,jsonb) TO authenticated;
COMMIT;
