-- This migration adds isolated friendship data. It does not touch game_saves, LIVE or player resources.
BEGIN;

CREATE TABLE IF NOT EXISTS public.world_friends (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sender_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  recipient_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','declined')),
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CHECK (sender_id <> recipient_id)
);
-- At most one relation per unordered pair, even for simultaneous crossed requests.
CREATE UNIQUE INDEX IF NOT EXISTS world_friends_pair_uq
  ON public.world_friends ((LEAST(sender_id,recipient_id)),(GREATEST(sender_id,recipient_id)));
CREATE INDEX IF NOT EXISTS world_friends_recipient_status
  ON public.world_friends(recipient_id,status,updated_at DESC);
CREATE INDEX IF NOT EXISTS world_friends_sender_status
  ON public.world_friends(sender_id,status,updated_at DESC);
ALTER TABLE public.world_friends ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.world_friends FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE public.world_friends_id_seq FROM PUBLIC,anon,authenticated;

-- Return only relationships involving the signed-in user; no emails or unrelated data.
CREATE OR REPLACE FUNCTION public.world_friends_list()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := auth.uid();
  v_rows jsonb;
  v_pending int;
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  SELECT count(*)::integer INTO v_pending
  FROM public.world_friends WHERE recipient_id=v_uid AND status='pending';

  SELECT COALESCE(jsonb_agg(t.item ORDER BY t.ord DESC,t.id DESC),'[]'::jsonb)
  INTO v_rows FROM (
    SELECT f.id, f.updated_at AS ord,
      jsonb_build_object(
        'id',f.id,
        'user_id',CASE WHEN f.sender_id=v_uid THEN f.recipient_id ELSE f.sender_id END,
        'name',COALESCE(w.name,'Jucător'),
        'direction',CASE WHEN f.sender_id=v_uid THEN 'outgoing' ELSE 'incoming' END,
        'status',f.status,
        'at',(extract(epoch from f.updated_at)*1000)::bigint
      ) AS item
    FROM public.world_friends f
    LEFT JOIN public.world_players w
      ON w.user_id=CASE WHEN f.sender_id=v_uid THEN f.recipient_id ELSE f.sender_id END
    WHERE (f.sender_id=v_uid OR f.recipient_id=v_uid)
      AND f.status IN ('accepted','pending')
    ORDER BY f.updated_at DESC,f.id DESC LIMIT 150
  ) t;
  RETURN jsonb_build_object('requests',v_pending,'items',v_rows);
END
$fn$;

CREATE OR REPLACE FUNCTION public.world_friends_request(p_target uuid)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE
  v_uid uuid := auth.uid();
  v_row public.world_friends%ROWTYPE;
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  IF p_target IS NULL OR p_target=v_uid THEN
    RAISE EXCEPTION 'Nu îți poți trimite cerere de prietenie.';
  END IF;
  IF NOT EXISTS(SELECT 1 FROM public.world_players WHERE user_id=v_uid)
      OR NOT EXISTS(SELECT 1 FROM public.world_players WHERE user_id=p_target) THEN
    RAISE EXCEPTION 'Ambii jucători trebuie să existe în Lume.';
  END IF;
  -- Serialize concurrent and crossed requests for this pair, including declines and removes.
  PERFORM pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(
      LEAST(v_uid,p_target)::text || ':' || GREATEST(v_uid,p_target)::text, 7753));
  SELECT * INTO v_row FROM public.world_friends
    WHERE LEAST(sender_id,recipient_id)=LEAST(v_uid,p_target)
      AND GREATEST(sender_id,recipient_id)=GREATEST(v_uid,p_target)
    FOR UPDATE;
  IF FOUND THEN
    IF v_row.status='accepted' THEN RAISE EXCEPTION 'Sunteți deja prieteni.'; END IF;
    IF v_row.status='pending' THEN
      RAISE EXCEPTION 'Există deja o cerere între voi. Verifică lista de prieteni.';
    END IF;
    -- A declined request may be sent again, but not repeatedly in a short period.
    IF v_row.updated_at > clock_timestamp()-interval '24 hours' THEN
      RAISE EXCEPTION 'Poți trimite o altă cerere peste 24 de ore.';
    END IF;
    UPDATE public.world_friends SET sender_id=v_uid,recipient_id=p_target,
      status='pending',created_at=clock_timestamp(),updated_at=clock_timestamp()
      WHERE id=v_row.id;
  ELSE
    -- Limit outstanding requests and new requests in a day.
    IF (SELECT count(*) FROM public.world_friends
        WHERE sender_id=v_uid AND status='pending')>=20 THEN
      RAISE EXCEPTION 'Ai prea multe cereri în așteptare.';
    END IF;
    INSERT INTO public.world_friends(sender_id,recipient_id)
    VALUES (v_uid,p_target);
  END IF;
  RETURN jsonb_build_object('ok',true);
END
$fn$;

CREATE OR REPLACE FUNCTION public.world_friends_respond(p_id bigint,p_accept boolean)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE v_uid uuid := auth.uid();
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  UPDATE public.world_friends
    SET status=CASE WHEN p_accept IS TRUE THEN 'accepted' ELSE 'declined' END,
        updated_at=clock_timestamp()
    WHERE id=p_id AND recipient_id=v_uid AND status='pending';
  IF NOT FOUND THEN RAISE EXCEPTION 'Cererea nu mai este disponibilă.'; END IF;
  RETURN jsonb_build_object('ok',true);
END
$fn$;

CREATE OR REPLACE FUNCTION public.world_friends_remove(p_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $fn$
DECLARE v_uid uuid := auth.uid();
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  -- Only participants can remove an accepted friendship or cancel their own outgoing request.
  DELETE FROM public.world_friends
   WHERE id=p_id AND
     ((status='accepted' AND (sender_id=v_uid OR recipient_id=v_uid))
      OR (status='pending' AND sender_id=v_uid));
  IF NOT FOUND THEN RAISE EXCEPTION 'Nu poți anula această relație.'; END IF;
  RETURN jsonb_build_object('ok',true);
END
$fn$;

REVOKE ALL ON FUNCTION public.world_friends_list() FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.world_friends_request(uuid) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.world_friends_respond(bigint,boolean) FROM PUBLIC,anon,authenticated;
REVOKE ALL ON FUNCTION public.world_friends_remove(bigint) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.world_friends_list() TO authenticated;
GRANT EXECUTE ON FUNCTION public.world_friends_request(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.world_friends_respond(bigint,boolean) TO authenticated;
GRANT EXECUTE ON FUNCTION public.world_friends_remove(bigint) TO authenticated;
COMMIT;

