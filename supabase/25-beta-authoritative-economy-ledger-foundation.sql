    'authenticated',
    'public.beta_economy_apply_internal(uuid,text,text,bigint,bigint,bigint)',
    'EXECUTE') AS mutation_not_exposed,
  has_function_privilege(
    'authenticated','public.beta_economy_status()','EXECUTE'
  ) AS own_status_callable;
