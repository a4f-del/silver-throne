-- Un cont apare doar printr-o operatiune INTERNA executata de o functie
-- server-side de incredere. Valorile nu sunt citite din game_saves.
CREATE TABLE IF NOT EXISTS public.beta_economy_accounts (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  gold bigint NOT NULL DEFAULT 0 CHECK (gold >= 0 AND gold <= 1000000000000),
  ore bigint NOT NULL DEFAULT 0 CHECK (ore >= 0 AND ore <= 1000000000000),
  xp bigint NOT NULL DEFAULT 0 CHECK (xp >= 0 AND xp <= 1000000000000),
  revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
  state text NOT NULL DEFAULT 'shadow' CHECK (state IN ('shadow','active')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Fiecare cheie de eveniment este aplicata cel mult o singura data, chiar
-- si la retry/concurenta. Pastreaza soldurile DUPA tranzactie.
CREATE TABLE IF NOT EXISTS public.beta_economy_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES public.beta_economy_accounts(user_id) ON DELETE CASCADE,
  event_key text NOT NULL CHECK (length(event_key) BETWEEN 3 AND 120),
  source text NOT NULL CHECK (source IN (
    'migration','admin_adjustment','dungeon_verified','pvp_verified',
    'forge_verified','market_verified','trone_verified'
  )),
  gold_delta bigint NOT NULL DEFAULT 0,
  ore_delta bigint NOT NULL DEFAULT 0,
  xp_delta bigint NOT NULL DEFAULT 0,
  gold_after bigint NOT NULL CHECK (gold_after >= 0),
  ore_after bigint NOT NULL CHECK (ore_after >= 0),
  xp_after bigint NOT NULL CHECK (xp_after >= 0),
  revision bigint NOT NULL CHECK (revision > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT beta_economy_ledger_event_unique UNIQUE (user_id,event_key)
);

CREATE INDEX IF NOT EXISTS beta_economy_ledger_user_recent
  ON public.beta_economy_ledger(user_id,id DESC);

ALTER TABLE public.beta_economy_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.beta_economy_ledger ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.beta_economy_accounts,
  public.beta_economy_ledger FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.beta_economy_ledger_id_seq
  FROM PUBLIC, anon, authenticated;

-- NU oferi EXECUTE clientilor pentru aceasta functie. Ulterior, numai
-- RPC-uri server-side care valideaza o actiune reala o vor apela.
-- NU apela niciodata cu valori provenite direct dintr-un payload de jucator.
CREATE OR REPLACE FUNCTION public.beta_economy_apply_internal(
  p_user uuid, p_event_key text, p_source text,
  p_gold_delta bigint, p_ore_delta bigint, p_xp_delta bigint
) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $apply$
DECLARE
  v_account public.beta_economy_accounts%ROWTYPE;
  v_old public.beta_economy_ledger%ROWTYPE;
  v_gold bigint;
  v_ore bigint;
  v_xp bigint;
  v_revision bigint;
  v_dg bigint := coalesce(p_gold_delta,0);
  v_do bigint := coalesce(p_ore_delta,0);
  v_dx bigint := coalesce(p_xp_delta,0);
BEGIN
  IF p_user IS NULL OR p_event_key IS NULL
     OR length(p_event_key) NOT BETWEEN 3 AND 120
     OR p_source IS NULL
     OR p_source NOT IN (
       'migration','admin_adjustment','dungeon_verified',
       'pvp_verified','forge_verified','market_verified','trone_verified'
     ) THEN
    RAISE EXCEPTION 'Eveniment economic invalid.';
  END IF;
  IF abs(v_dg::numeric) > 1000000000000
     OR abs(v_do::numeric) > 1000000000000
     OR abs(v_dx::numeric) > 1000000000000
     OR (v_dg=0 AND v_do=0 AND v_dx=0) THEN
    RAISE EXCEPTION 'Tranzactie economica invalida.';
  END IF;

  INSERT INTO public.beta_economy_accounts(user_id)
    VALUES(p_user) ON CONFLICT(user_id) DO NOTHING;
  SELECT * INTO STRICT v_account
    FROM public.beta_economy_accounts WHERE user_id=p_user FOR UPDATE;

  -- Lockul contului serializeaza doua operatiuni cu aceeasi cheie, inclusiv
  -- retry-uri simultane. Aceeasi cheie cu alt payload este refuzata.
  SELECT * INTO v_old FROM public.beta_economy_ledger
    WHERE user_id=p_user AND event_key=p_event_key;
  IF FOUND THEN
    IF v_old.source IS DISTINCT FROM p_source
       OR v_old.gold_delta<>v_dg
       OR v_old.ore_delta<>v_do
       OR v_old.xp_delta<>v_dx THEN
      RAISE EXCEPTION 'Cheie economica refolosita cu alte valori.';
    END IF;
    RETURN jsonb_build_object(
      'ok',true,'already',true,'revision',v_old.revision,
      'gold',v_old.gold_after,'ore',v_old.ore_after,'xp',v_old.xp_after);
  END IF;

  -- Numeric pentru calcul sigur inainte de cast la bigint si check-urile SQL.
  IF v_account.gold::numeric+v_dg NOT BETWEEN 0 AND 1000000000000
     OR v_account.ore::numeric+v_do NOT BETWEEN 0 AND 1000000000000
     OR v_account.xp::numeric+v_dx NOT BETWEEN 0 AND 1000000000000 THEN
    RAISE EXCEPTION 'Sold insuficient sau in afara limitelor.';
  END IF;

  v_gold:=v_account.gold+v_dg;
  v_ore:=v_account.ore+v_do;
  v_xp:=v_account.xp+v_dx;
  v_revision:=v_account.revision+1;

  UPDATE public.beta_economy_accounts SET
    gold=v_gold,ore=v_ore,xp=v_xp,revision=v_revision,updated_at=now()
  WHERE user_id=p_user;

  INSERT INTO public.beta_economy_ledger(
    user_id,event_key,source,gold_delta,ore_delta,xp_delta,
    gold_after,ore_after,xp_after,revision
  ) VALUES(
    p_user,p_event_key,p_source,v_dg,v_do,v_dx,
    v_gold,v_ore,v_xp,v_revision
  );

  RETURN jsonb_build_object(
    'ok',true,'already',false,'revision',v_revision,
    'gold',v_gold,'ore',v_ore,'xp',v_xp);
END
$apply$;

-- Citire strict pentru contul autenticat, fara acces la conturile altora.
-- Infrastructura este in SHADOW: NU arata aceasta ca portofel utilizabil.
CREATE OR REPLACE FUNCTION public.beta_economy_status()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $status$
DECLARE
  v_uid uuid := auth.uid();
  v_account public.beta_economy_accounts%ROWTYPE;
BEGIN
  IF v_uid IS NULL OR NOT public.is_beta_admin() THEN
    RAISE EXCEPTION 'Acces BETA neautorizat';
  END IF;
  SELECT * INTO v_account FROM public.beta_economy_accounts
    WHERE user_id=v_uid;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ready',true,'enrolled',false,
      'mode','shadow','authoritative_for_game',false);
  END IF;
  RETURN jsonb_build_object(
    'ready',true,'enrolled',true,'mode',v_account.state,
    'authoritative_for_game',false,
    'gold',v_account.gold,'ore',v_account.ore,'xp',v_account.xp,
    'revision',v_account.revision);
END
$status$;

